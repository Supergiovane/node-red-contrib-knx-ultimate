const normalizeLanguage = value => {
  const raw = String(value || '').trim().toLowerCase()
  if (raw.startsWith('it')) return 'it'
  if (raw.startsWith('de')) return 'de'
  if (raw.startsWith('fr')) return 'fr'
  if (raw.startsWith('es')) return 'es'
  if (raw.startsWith('zh')) return 'zh-CN'
  return 'en'
}

const oneLine = (value, fallback = '') => {
  const text = String(value === undefined || value === null ? '' : value).replace(/\s+/g, ' ').trim()
  return (text || fallback).slice(0, 500)
}

const asArray = value => Array.isArray(value) ? value : []

const formatDate = (value, language) => {
  const raw = oneLine(value)
  if (!raw) return '—'
  const date = new Date(raw)
  if (Number.isNaN(date.getTime())) return raw
  try {
    return new Intl.DateTimeFormat(language, { dateStyle: 'medium', timeStyle: 'short' }).format(date)
  } catch (error) {
    return raw
  }
}

const formatMinute = value => {
  const minute = Math.max(0, Math.min(1439, Math.round(Number(value) || 0)))
  return `${String(Math.floor(minute / 60)).padStart(2, '0')}:${String(minute % 60).padStart(2, '0')}`
}

const formatPercent = value => `${Math.round(Math.max(0, Math.min(1, Number(value) || 0)) * 100)}%`

export function parseCerebrumMemoryJson (value) {
  const text = String(value || '').trim()
  const match = text.match(/<!-- KNX_AI_HOME_MEMORY_V1\s*\n([\s\S]*?)\nKNX_AI_HOME_MEMORY_END -->/)
  const jsonText = match ? match[1].trim() : text
  if (!jsonText) throw new Error('Cerebrum memory is empty')
  const parsed = JSON.parse(jsonText)
  if (!parsed || typeof parsed !== 'object' || Array.isArray(parsed)) throw new Error('Cerebrum memory must contain one JSON object')
  return parsed
}

export function formatCerebrumMemoryJson (value) {
  return `${JSON.stringify(parseCerebrumMemoryJson(value), null, 2)}\n`
}

export function replaceCerebrumMemoryJsonBlock (fileContent, jsonContent) {
  const prettyJson = JSON.stringify(parseCerebrumMemoryJson(jsonContent), null, 2)
  const block = `<!-- KNX_AI_HOME_MEMORY_V1\n${prettyJson}\nKNX_AI_HOME_MEMORY_END -->`
  const source = String(fileContent || '')
  return /<!-- KNX_AI_HOME_MEMORY_V1\s*\n[\s\S]*?\nKNX_AI_HOME_MEMORY_END -->/.test(source)
    ? source.replace(/<!-- KNX_AI_HOME_MEMORY_V1\s*\n[\s\S]*?\nKNX_AI_HOME_MEMORY_END -->/, block)
    : `${block}\n`
}

export function formatCerebrumMemorySimpleText (memoryValue, { language = 'en' } = {}) {
  const memory = typeof memoryValue === 'string' ? parseCerebrumMemoryJson(memoryValue) : (memoryValue || {})
  const lang = normalizeLanguage(language)
  const t = COPY[lang] || COPY.en
  const habits = asArray(memory.habits)
  const decisions = asArray(memory.habitDecisions)
  const states = asArray(memory.states)
  const observations = asArray(memory.observations)
  const notifications = asArray(memory.notifications)
  const objects = asArray(memory.semanticObjects)
  const habitLabels = new Map(habits.map(habit => [String((habit && habit.id) || ''), oneLine(habit && (habit.label || habit.objectId || habit.ga), t.unknown)]))
  const lines = [
    t.title,
    t.readOnly,
    '',
    `${t.updated}: ${formatDate(memory.updatedAt, lang)}`,
    `${t.summary}: ${habits.length} ${t.habitsWord} · ${decisions.length} ${t.decisionsWord} · ${states.length} ${t.statesWord} · ${objects.length} ${t.objectsWord}`
  ]

  const addSection = (title, items, render) => {
    lines.push('', title.toUpperCase())
    if (!items.length) {
      lines.push(t.none)
      return
    }
    items.forEach((item, index) => render(item || {}, index))
  }

  addSection(t.habits, habits, (habit, index) => {
    const label = oneLine(habit.label || habit.objectId || habit.ga, t.unknown)
    const status = t[String(habit.status || '') === 'pending_confirmation' ? 'pending' : String(habit.status || '')] || oneLine(habit.status, t.unknown)
    lines.push(`${index + 1}. ${label}`)
    lines.push(`   ${t.status}: ${status}`)
    if (habit.type === 'temporal_state_pattern') {
      const override = habit.userOverride && typeof habit.userOverride === 'object' ? habit.userOverride : {}
      const minute = override.timeMinute !== null && override.timeMinute !== undefined ? override.timeMinute : habit.averageMinuteOfDay
      const dayType = oneLine(override.dayType || habit.dayType)
      lines.push(`   ${t.pattern}: ${oneLine(override.value || habit.value, t.unknown)} · ${formatMinute(minute)} · ${t[dayType] || dayType || t.unknown}`)
      lines.push(`   ${t.evidence}: ${Math.max(0, Number(habit.samples) || 0)} ${t.observationsCount} · ${Math.max(0, Number(habit.observationDays) || 0)} ${t.distinctDays} · ${Math.max(0, Number(habit.observationSpanDays) || 0)} ${t.acrossDays} · ${formatPercent(habit.confidence)} ${t.confidence}`)
      if (override.note || habit.userMessage) lines.push(`   ${t.note}: ${oneLine(override.note || habit.userMessage)}`)
      if (habit.proposalMessage) lines.push(`   ${t.proposal}: ${oneLine(habit.proposalMessage)}`)
    } else {
      lines.push(`   ${t.averageOpen}: ${Math.max(0, Number(habit.averageMinutes) || 0).toFixed(1)} ${t.minutes} · ${Math.max(0, Number(habit.samples) || 0)} ${t.observationsCount}`)
    }
  })

  addSection(t.decisions, decisions, (decision, index) => {
    const operation = t[oneLine(decision.operation)] || oneLine(decision.operation, t.unknown)
    const label = habitLabels.get(String(decision.habitId || '')) || t.unknown
    lines.push(`${index + 1}. ${formatDate(decision.at, lang)} · ${operation} · ${label}${decision.userMessage ? ` — ${oneLine(decision.userMessage)}` : ''}`)
  })

  addSection(t.states, states, (state, index) => {
    const details = [
      state.area ? `${t.area}: ${oneLine(state.area)}` : '',
      state.source ? `${t.source}: ${oneLine(state.source)}` : '',
      state.observedAt ? `${t.observed}: ${formatDate(state.observedAt, lang)}` : '',
      state.verifiedAt ? `${t.verified}: ${formatDate(state.verifiedAt, lang)}` : ''
    ].filter(Boolean).join(' · ')
    lines.push(`${index + 1}. ${oneLine(state.label || state.objectId, t.unknown)}: ${oneLine(state.value, t.unknown)}${details ? ` · ${details}` : ''}`)
  })

  addSection(t.observations, observations, (observation, index) => {
    lines.push(`${index + 1}. ${formatDate(observation.at, lang)} · ${oneLine(observation.label || observation.ga, t.unknown)}: ${oneLine(observation.event || observation.value || observation.type, t.unknown)}`)
  })

  addSection(t.notifications, notifications, (notification, index) => {
    lines.push(`${index + 1}. ${formatDate(notification.at, lang)} · ${oneLine(notification.label || notification.ga || notification.type, t.unknown)}: ${oneLine(notification.message || notification.reason || notification.type, t.unknown)}`)
  })

  addSection(t.objects, objects, (object, index) => {
    const details = [object.area ? `${t.area}: ${oneLine(object.area)}` : '', object.kind ? oneLine(object.kind) : ''].filter(Boolean).join(' · ')
    lines.push(`${index + 1}. ${oneLine(object.label || object.ga, t.unknown)}${details ? ` · ${details}` : ''}`)
  })

  const reconciler = memory.reconciler && typeof memory.reconciler === 'object' ? memory.reconciler : {}
  lines.push('', t.refresh.toUpperCase())
  lines.push(`${t.lastTick}: ${formatDate(reconciler.lastTickAt, lang)}`)
  lines.push(`${t.haRefreshes}: ${Math.max(0, Number(reconciler.homeAssistantRefreshCount) || 0)} · ${Math.max(0, Number(reconciler.homeAssistantErrorCount) || 0)} ${t.haErrors}`)
  lines.push(`${t.knxReads}: ${Math.max(0, Number(reconciler.knxReadCount) || 0)}`)

  return `${lines.join('\n')}\n`
}
